"""Reproduce every comparison and save actual per-example evidence."""
from collections import Counter
import json
import platform
from pathlib import Path

import sklearn

from dataset import (SAMPLE_POSTS, TRUE_LABELS, STARTER_POSTS, STARTER_LABELS,
                     STRESS_POSTS, STRESS_LABELS, validate_dataset)
from ml_experiments import train_ml_model, predict_single_text
from mood_analyzer import MoodAnalyzer


def measure(posts, labels, predictor):
    """Collect predictions and accuracy only after validating aligned labels."""
    validate_dataset(posts, labels)
    rows = [{"text": text, "expected": expected, "predicted": predictor(text)}
            for text, expected in zip(posts, labels)]
    correct = sum(row["expected"] == row["predicted"] for row in rows)
    return {"correct": correct, "total": len(rows),
            "accuracy": correct / len(rows) if rows else 0.0, "rows": rows}


def run_experiments():
    """Compare one focused rule change and fixed stress sets across training choices."""
    baseline = MoodAnalyzer(handle_negation=False)
    improved = MoodAnalyzer(handle_negation=True)
    vectorizer, model = train_ml_model(SAMPLE_POSTS, TRUE_LABELS)
    seed_vectorizer, seed_model = train_ml_model(STARTER_POSTS, STARTER_LABELS)
    altered_labels = TRUE_LABELS.copy()
    altered_labels[len(STARTER_POSTS)] = "positive"  # Deliberate disagreement on sarcasm.
    altered_vectorizer, altered_model = train_ml_model(SAMPLE_POSTS, altered_labels)
    models = {
        "keyword_baseline": baseline.predict_label,
        "negation_improvement": improved.predict_label,
        "ml_seed6": lambda text: predict_single_text(text, seed_vectorizer, seed_model),
        "ml_expanded14": lambda text: predict_single_text(text, vectorizer, model),
        "ml_label_sensitivity": lambda text: predict_single_text(text, altered_vectorizer, altered_model),
    }
    report = {
        "evaluation_date": "2026-11-08",
        "python": platform.python_version(),
        "scikit_learn": sklearn.__version__,
        "labels_reviewed_by_student": True,
        "development_class_counts": dict(Counter(TRUE_LABELS)),
        "stress_class_counts": dict(Counter(STRESS_LABELS)),
        "stress_excluded_from_training": not (set(SAMPLE_POSTS) & set(STRESS_POSTS)),
        "expanded_ml_vocabulary": sorted(vectorizer.vocabulary_),
        "constant_positive_stress_reference": sum(label == "positive" for label in STRESS_LABELS) / len(STRESS_LABELS),
        "results": {},
    }
    for name, predictor in models.items():
        # Seed6 versus expanded14 are evaluated against the SAME fixed sets.
        report["results"][name] = {
            "development": measure(SAMPLE_POSTS, TRUE_LABELS, predictor),
            "stress": measure(STRESS_POSTS, STRESS_LABELS, predictor),
        }
    report["seed6_training"] = measure(STARTER_POSTS, STARTER_LABELS, models["ml_seed6"])
    report["diagnostics"] = [
        {"text": text, "expected": expected,
         "baseline": baseline.analyze(text), "improved": improved.analyze(text)}
        for text, expected in zip(STRESS_POSTS, STRESS_LABELS)
    ]
    root = Path(__file__).resolve().parent
    (root / "results.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = [
        "# Recorded evaluation", "",
        "Generated by python run_experiments.py; labels reviewed by the student.",
        "Development data informed the rules and trained the expanded ML model.",
        "Stress examples never enter model.fit(), but are small, selected diagnostics, not a benchmark.",
        "Do not interpret training accuracy as generalization.", "",
        "| Model | Development (14) | Stress (8) |",
        "| --- | --- | --- |",
    ]
    for name, result in report["results"].items():
        values = [f"{result[key]['correct']}/{result[key]['total']} ({result[key]['accuracy']:.1%})"
                  for key in ("development", "stress")]
        lines.append(f"| {name} | {values[0]} | {values[1]} |")
    lines += ["", "ml_seed6 development results include its 6 training posts plus 8 newly added posts.",
              "ml_label_sensitivity flips the training label for the sarcastic delay post only;",
              "it is a sensitivity experiment, not the accepted dataset or the shipped model.",
              "The stress set has 6 positive and 2 negative labels: always predicting positive scores 6/8 (75%).",
              "Both measured models fall below that reference here; the set has no neutral/mixed cases.",
              "Do not use these small, imbalanced results to rank overall model quality.",
              "", "## Per-example stress predictions", "",
              "| Text | Expected | Keyword | Negation | ML seed6 | ML expanded14 |",
              "| --- | --- | --- | --- | --- | --- |"]
    for i, text in enumerate(STRESS_POSTS):
        predictions = [report["results"][name]["stress"]["rows"][i]["predicted"]
                       for name in ("keyword_baseline", "negation_improvement", "ml_seed6", "ml_expanded14")]
        lines.append("| " + " | ".join([text, STRESS_LABELS[i]] + predictions) + " |")
    lines += ["", "## Negation diagnostics", ""]
    for item in report["diagnostics"]:
        details = item["improved"]
        lines += [f"### {item['text']}", f"Expected: {item['expected']}; baseline: {item['baseline']['label']}; improved: {details['label']}.",
                  f"Tokens: {details['tokens']}", f"Matches: {details['matches']}",
                  f"Ignored: {details['ignored']}", f"Score: {details['score']}", ""]
    (root / "evaluation_report.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    report = run_experiments()
    for name, result in report["results"].items():
        print(name + ": " + ", ".join(
            f"{key}={value['correct']}/{value['total']} ({value['accuracy']:.1%})"
            for key, value in result.items()))
    print("Saved results.json and evaluation_report.md.")
